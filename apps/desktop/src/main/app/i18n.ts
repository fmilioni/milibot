export type MainStringKey = keyof (typeof MAIN_STRINGS)['en']

export function mainText(
  language: Language,
  key: MainStringKey,
  params: Record<string, string | number> = {},
): string {
  return MAIN_STRINGS[language][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  )
}

export function systemLanguage(locale: string): Language {
  return locale.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en'
}
