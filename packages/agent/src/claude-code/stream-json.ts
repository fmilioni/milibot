import type { CliUsageWindow, LlmCallModelUsage, PatchHunk } from '@milibot/shared'

import type { TokenUsage } from '../llm/usage'

/** One entry of the `modelUsage` map of a `result` event. */
export type ClaudeModelUsage = LlmCallModelUsage

/** Subscription quota reported by `rate_limit_event` (times in epoch ms). */
export interface ClaudeRateLimit {
  status: string
  rateLimitType: string | null
  resetsAt: number | null
  windows: CliUsageWindow[]
}

/** What a native Edit/Write reported in `tool_use_result` (the file's full previous content is dropped). */
export interface ClaudeFileChange {
  filePath: string
  /** `create` for a new file written by Write. */
  kind: 'create' | 'update'
  hunks: PatchHunk[]
  /** Content of a created file (its hunks are empty). */
  content?: string
}

interface ClaudeToolResult {
  toolUseId: string
  isError: boolean
  text: string
  fileChange?: ClaudeFileChange
}

/**
 * Events of `claude -p --output-format stream-json --verbose [--include-partial-messages]`, reduced
 * to what Milibot consumes. Unknown event types are passed through as `other`.
 */
export type ClaudeCodeEvent =
  | {
      type: 'init'
      sessionId: string
      model: string | null
      mcpServers: Array<{ name: string; status: string }>
    }
  | { type: 'text_delta'; text: string }
  /** A tool call starts streaming its input (partial-messages mode); `index` is its content block. */
  | { type: 'tool_input_start'; index: number; id: string; name: string }
  /** A piece of the tool call's input JSON (not accumulated). */
  | { type: 'tool_input_delta'; index: number; partialJson: string }
  | { type: 'tool_input_stop'; index: number }
  /** Start of a new model message (partial-messages mode). */
  | { type: 'message_start' }
  | {
      type: 'assistant'
      messageId: string | null
      text: string
      toolUses: Array<{ id: string; name: string; input: unknown }>
      /** Set for sub-agent (Task) messages. */
      parentToolUseId: string | null
      /** Generated by Claude Code itself (e.g. "Not logged in"), not by the model; repeated in `result`. */
      synthetic: boolean
      /** Prompt tokens of the API request that produced this message (input + cache read + cache write). */
      contextTokens: number | null
      /** Usage of that request as the message reports it (its output count may still grow). */
      usage: TokenUsage | null
    }
  | { type: 'tool_results'; results: ClaudeToolResult[] }
  /** A user message written to stdin, echoed (`--replay-user-messages`) when the CLI takes it in. */
  | { type: 'user_replay'; text: string }
  | {
      type: 'result'
      subtype: string
      isError: boolean
      text: string
      sessionId: string | null
      costUsd: number | null
      durationMs: number | null
      numTurns: number | null
      /** Usage of this turn (the requests since the last input). */
      usage: TokenUsage
      /**
       * Per-model usage and cost. Like `costUsd`, it is cumulative over the life of the process
       * (all turns of a stream-json session), not per turn.
       */
      modelUsage: ClaudeModelUsage[]
      /** e.g. "No conversation found with session ID: …" when `--resume` fails. */
      errors: string[]
    }
  | { type: 'rate_limit'; info: ClaudeRateLimit }
  | { type: 'other'; raw: unknown }

interface RawContentBlock {
  type?: string
  text?: string
  id?: string
  name?: string
  input?: unknown
  tool_use_id?: string
  is_error?: boolean
  content?: unknown
}

function blocks(message: unknown): RawContentBlock[] {
  const content = (message as { content?: unknown } | undefined)?.content
  if (typeof content === 'string') return [{ type: 'text', text: content }]
  return Array.isArray(content) ? (content as RawContentBlock[]) : []
}

function resultText(content: unknown): string {
  if (typeof content === 'string') return content
  if (Array.isArray(content)) {
    return content
      .map((c: RawContentBlock) => (c.type === 'text' ? (c.text ?? '') : c.type === 'image' ? '[image]' : ''))
      .join('\n')
  }
  return ''
}

function isHunk(value: unknown): value is PatchHunk {
  const h = value as Partial<PatchHunk> | null
  return (
    !!h &&
    typeof h.oldStart === 'number' &&
    typeof h.oldLines === 'number' &&
    typeof h.newStart === 'number' &&
    typeof h.newLines === 'number' &&
    Array.isArray(h.lines) &&
    h.lines.every((l) => typeof l === 'string')
  )
}

function fileChangeOf(raw: unknown): ClaudeFileChange | undefined {
  const r = raw as Record<string, unknown> | null
  if (!r || typeof r !== 'object' || typeof r.filePath !== 'string' || !Array.isArray(r.structuredPatch)) {
    return undefined
  }
  const hunks = r.structuredPatch.filter(isHunk)
  const kind = r.type === 'create' ? 'create' : 'update'
  return {
    filePath: r.filePath,
    kind,
    hunks,
    ...(kind === 'create' && !hunks.length && typeof r.content === 'string' ? { content: r.content } : {}),
  }
}

function num(value: unknown): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : 0
}

/** Anthropic-style usage (input excludes cache reads/writes) mapped to the stored buckets. */
function cliUsage(raw: unknown): TokenUsage {
  const u = (raw ?? {}) as Record<string, unknown>
  const reasoning = num(
    (u.output_tokens_details as Record<string, unknown> | null | undefined)?.thinking_tokens,
  )
  return {
    inputTokens: num(u.input_tokens),
    cachedReadTokens: num(u.cache_read_input_tokens),
    cacheWriteTokens: num(u.cache_creation_input_tokens),
    outputTokens: Math.max(0, num(u.output_tokens) - reasoning),
    reasoningTokens: reasoning,
  }
}

/** `modelUsage` of a `result` event; thinking tokens are split out of output (disjoint buckets). */
function parseModelUsage(raw: unknown): ClaudeModelUsage[] {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return []
  return Object.entries(raw as Record<string, Record<string, unknown> | null>).map(([model, u]) => {
    const output = num(u?.outputTokens)
    const reasoning = Math.min(output, num(u?.thinkingTokens))
    return {
      model,
      inputTokens: num(u?.inputTokens),
      cachedReadTokens: num(u?.cacheReadInputTokens),
      cacheWriteTokens: num(u?.cacheCreationInputTokens),
      outputTokens: output - reasoning,
      reasoningTokens: reasoning,
      costUsd: typeof u?.costUSD === 'number' && Number.isFinite(u.costUSD) ? u.costUSD : null,
      webSearchRequests: num(u?.webSearchRequests),
    }
  })
}

/** Usage of one turn out of two cumulative snapshots of the same process (`prev` may be empty). */
export function modelUsageDelta(current: ClaudeModelUsage[], prev: ClaudeModelUsage[]): ClaudeModelUsage[] {
  const before = new Map(prev.map((m) => [m.model, m]))
  const delta = current.map((m) => {
    const p = before.get(m.model)
    if (!p) return m
    const diff = (a: number, b: number) => Math.max(0, a - b)
    return {
      model: m.model,
      inputTokens: diff(m.inputTokens, p.inputTokens),
      cachedReadTokens: diff(m.cachedReadTokens, p.cachedReadTokens),
      cacheWriteTokens: diff(m.cacheWriteTokens, p.cacheWriteTokens),
      outputTokens: diff(m.outputTokens, p.outputTokens),
      reasoningTokens: diff(m.reasoningTokens, p.reasoningTokens),
      costUsd: m.costUsd === null ? null : Math.max(0, m.costUsd - (p.costUsd ?? 0)),
      webSearchRequests: diff(m.webSearchRequests, p.webSearchRequests),
    }
  })
  return delta.filter(
    (m) =>
      m.inputTokens + m.cachedReadTokens + m.cacheWriteTokens + m.outputTokens + m.reasoningTokens > 0 ||
      (m.costUsd ?? 0) > 0,
  )
}

function epochMs(seconds: unknown): number | null {
  return typeof seconds === 'number' && Number.isFinite(seconds) ? Math.round(seconds * 1000) : null
}

function parseRateLimit(raw: unknown): ClaudeRateLimit | null {
  const info = raw as Record<string, unknown> | null | undefined
  if (!info || typeof info.status !== 'string') return null
  const windows = (info.unifiedWindows ?? {}) as Record<string, Record<string, unknown> | null>
  return {
    status: info.status,
    rateLimitType: typeof info.rateLimitType === 'string' ? info.rateLimitType : null,
    resetsAt: epochMs(info.resetsAt),
    windows: Object.entries(windows)
      .filter(([, w]) => typeof w?.utilization === 'number')
      .map(([id, w]) => ({ id, utilization: num(w?.utilization), resetsAt: epochMs(w?.resetsAt) })),
  }
}

export function parseStreamJsonLine(line: string): ClaudeCodeEvent | null {
  const trimmed = line.trim()
  if (!trimmed.startsWith('{')) return null
  let raw: Record<string, unknown>
  try {
    raw = JSON.parse(trimmed) as Record<string, unknown>
  } catch {
    return null
  }
  switch (raw.type) {
    case 'system':
      if (raw.subtype === 'init' && typeof raw.session_id === 'string') {
        return {
          type: 'init',
          sessionId: raw.session_id,
          model: typeof raw.model === 'string' ? raw.model : null,
          mcpServers: Array.isArray(raw.mcp_servers)
            ? (raw.mcp_servers as Array<{ name: string; status: string }>)
            : [],
        }
      }
      return { type: 'other', raw }
    case 'stream_event': {
      const event = raw.event as
        | {
            type?: string
            index?: number
            delta?: { type?: string; text?: string; partial_json?: string }
            content_block?: { type?: string; id?: string; name?: string }
          }
        | undefined
      if (raw.parent_tool_use_id) return { type: 'other', raw }
      if (event?.type === 'message_start') return { type: 'message_start' }
      if (event?.type === 'content_block_delta' && event.delta?.type === 'text_delta' && event.delta.text) {
        return { type: 'text_delta', text: event.delta.text }
      }
      const index = typeof event?.index === 'number' ? event.index : null
      if (index === null) return { type: 'other', raw }
      if (event?.type === 'content_block_start' && event.content_block?.type === 'tool_use') {
        return {
          type: 'tool_input_start',
          index,
          id: event.content_block.id ?? '',
          name: event.content_block.name ?? '',
        }
      }
      if (
        event?.type === 'content_block_delta' &&
        event.delta?.type === 'input_json_delta' &&
        event.delta.partial_json
      ) {
        return { type: 'tool_input_delta', index, partialJson: event.delta.partial_json }
      }
      if (event?.type === 'content_block_stop') return { type: 'tool_input_stop', index }
      return { type: 'other', raw }
    }
    case 'assistant': {
      const message = raw.message as { id?: string; model?: string; usage?: unknown } | undefined
      const content = blocks(message)
      const usage = message?.usage ? cliUsage(message.usage) : null
      return {
        type: 'assistant',
        messageId: message?.id ?? null,
        text: content
          .filter((b) => b.type === 'text')
          .map((b) => b.text ?? '')
          .join(''),
        toolUses: content
          .filter((b) => b.type === 'tool_use')
          .map((b) => ({ id: b.id ?? '', name: b.name ?? '', input: b.input ?? {} })),
        parentToolUseId: typeof raw.parent_tool_use_id === 'string' ? raw.parent_tool_use_id : null,
        synthetic: message?.model === '<synthetic>' || typeof raw.error === 'string',
        contextTokens: usage ? usage.inputTokens + usage.cachedReadTokens + usage.cacheWriteTokens : null,
        usage,
      }
    }
    case 'user': {
      if (raw.isReplay === true)
        return {
          type: 'user_replay',
          text: blocks(raw.message)
            .filter((b) => b.type === 'text')
            .map((b) => b.text ?? '')
            .join(''),
        }
      const results: ClaudeToolResult[] = blocks(raw.message)
        .filter((b) => b.type === 'tool_result')
        .map((b) => ({
          toolUseId: b.tool_use_id ?? '',
          isError: b.is_error === true,
          text: resultText(b.content),
        }))
      const fileChange = fileChangeOf(raw.tool_use_result ?? raw.toolUseResult)
      const only = results.length === 1 ? results[0] : undefined
      if (only && fileChange && !only.isError) only.fileChange = fileChange
      return results.length ? { type: 'tool_results', results } : { type: 'other', raw }
    }
    case 'rate_limit_event': {
      const info = parseRateLimit(raw.rate_limit_info)
      return info ? { type: 'rate_limit', info } : { type: 'other', raw }
    }
    case 'result':
      return {
        type: 'result',
        subtype: typeof raw.subtype === 'string' ? raw.subtype : 'unknown',
        isError: raw.is_error === true,
        text: typeof raw.result === 'string' ? raw.result : '',
        sessionId: typeof raw.session_id === 'string' ? raw.session_id : null,
        costUsd: typeof raw.total_cost_usd === 'number' ? raw.total_cost_usd : null,
        durationMs: typeof raw.duration_ms === 'number' ? raw.duration_ms : null,
        numTurns: typeof raw.num_turns === 'number' ? raw.num_turns : null,
        usage: cliUsage(raw.usage),
        modelUsage: parseModelUsage(raw.modelUsage),
        errors: Array.isArray(raw.errors) ? raw.errors.filter((e): e is string => typeof e === 'string') : [],
      }
    default:
      return { type: 'other', raw }
  }
}

export function userInputLine(text: string): string {
  return `${JSON.stringify({ type: 'user', message: { role: 'user', content: [{ type: 'text', text }] } })}\n`
}
