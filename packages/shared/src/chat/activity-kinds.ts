/** A readable tool name when nothing else is known: "list_bots" → "list bots", "NotebookRead" → "Notebook Read". */
export function humanToolName(name: string): string {
  return name
    .replace(/^mcp__[^_]+__/, '')
    .replace(/[_-]+/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .trim()
}
